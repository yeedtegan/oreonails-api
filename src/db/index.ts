pg.types.setTypeParser(1700, (v) => Number(v)); // numeric — money, ratings
pg.types.setTypeParser(1184, (v) => new Date(v).toISOString()); // timestamptz → ISO string
pg.types.setTypeParser(1082, (v) => v); // date → "YYYY-MM-DD"


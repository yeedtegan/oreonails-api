export const pool = new pg.Pool({ connectionString: config.databaseUrl, max: config.databasePoolSize });

type Client = pg.Pool | pg.PoolClient;
/** Set while inside `tx()`, so every query in the callback runs on the transaction's connection. */
const txClient = new AsyncLocalStorage<pg.PoolClient>();
const client = (): Client => txClient.getStore() ?? pool;

export type Param = string | number | boolean | null | undefined | string[] | number[];

/** Run a statement. Use $1, $2… placeholders. */
export function query(sql: string, params: Param[] = []) {
  return client().query(sql, params);
}
export async function all<T>(sql: string, params: Param[] = []): Promise<T[]> {
  return (await client().query(sql, params)).rows as T[];
}
export async function one<T>(sql: string, params: Param[] = []): Promise<T | undefined> {
  return (await client().query(sql, params)).rows[0] as T | undefined;
}
/** Number of rows changed by an INSERT/UPDATE/DELETE. */
export async function run(sql: string, params: Param[] = []): Promise<number> {
  return (await client().query(sql, params)).rowCount ?? 0;
}

/** Collects positional parameters for dynamically built SQL: `where.push(\`x = ${p.add(v)}\`)`. */
export class Params {
  readonly values: Param[] = [];
  add(v: Param) {
    this.values.push(v);
    return `$${this.values.length}`;
  }
}

/** Run `fn` inside a transaction; rolls back on throw. Nested calls join the outer transaction. */
export async function tx<T>(fn: () => Promise<T>): Promise<T> {
  if (txClient.getStore()) return fn();
  const c = await pool.connect();
  try {
    await c.query("BEGIN");
    const out = await txClient.run(c, fn);
    await c.query("COMMIT");
    return out;
  } catch (e) {
    await c.query("ROLLBACK").catch(() => {});
    throw e;
  } finally {
    c.release();
  }
}

/** Creates tables and indexes if missing. Safe to run on every start. */
export async function migrate() {
  await pool.query(SCHEMA);
}

export async function getSetting<T>(key: string, fallback: T): Promise<T> {
  const row = await one<{ value: T }>("SELECT value FROM settings WHERE key = $1", [key]);
  return row ? row.value : fallback;
}

export async function isEmpty() {
  const row = await one<{ n: number }>("SELECT COUNT(*) AS n FROM products");
  return row!.n === 0;
}
